const SIGN_IMAGES = {
  Adds: 'pets/adds.png',
};

function getSignImage(name) {
  if (SIGN_IMAGES[name]) return SIGN_IMAGES[name];
  const label = name.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const fontSize = name.length > 12 ? 11 : name.length > 8 ? 13 : 15;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128"><rect width="128" height="128" rx="14" fill="#1f2937"/><rect x="8" y="8" width="112" height="112" rx="10" fill="#374151"/><text x="64" y="66" text-anchor="middle" dominant-baseline="middle" fill="#ffffff" font-family="Outfit,Arial,sans-serif" font-size="${fontSize}" font-weight="700">${label}</text></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

